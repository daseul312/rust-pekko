#[cfg(test)]
mod tests {
    use super::*;

    fn test_address(port: u16) -> RemoteAddress {
        RemoteAddress::tcp("test-system", "127.0.0.1", port)
    }

    fn test_target(port: u16, path: &str) -> WatchTarget {
        WatchTarget::new(test_address(port), path)
    }

    // === WatchTarget Tests ===

    #[test]
    fn test_watch_target_creation() {
        let target = test_target(2551, "/user/actor-a");
        assert_eq!(target.actor_path, "/user/actor-a");
        assert_eq!(target.address.port, 2551);
    }

    #[test]
    fn test_watch_target_equality() {
        let t1 = test_target(2551, "/user/a");
        let t2 = test_target(2551, "/user/a");
        let t3 = test_target(2552, "/user/a");
        assert_eq!(t1, t2);
        assert_ne!(t1, t3);
    }

    // === NodeStatus Tests ===

    #[test]
    fn test_node_status_checks() {
        assert!(!NodeStatus::Unknown.is_reachable());
        assert!(NodeStatus::Reachable.is_reachable());
        assert!(NodeStatus::Unreachable { since: Instant::now() }.is_unreachable());
        assert!(NodeStatus::Quarantined {
            since: Instant::now(),
            reason: QuarantineReason::ManualQuarantine,
        }.is_quarantined());
    }

    // === HeartbeatState Tests ===

    #[test]
    fn test_heartbeat_state_initial() {
        let hb = HeartbeatState::new();
        assert_eq!(hb.missed_count, 0);
        assert!(hb.rtt_samples.is_empty());
        assert!(hb.average_rtt().is_none());
    }

    #[test]
    fn test_heartbeat_record() {
        let mut hb = HeartbeatState::new();
        hb.record_heartbeat(Duration::from_millis(10));
        hb.record_heartbeat(Duration::from_millis(20));
        hb.record_heartbeat(Duration::from_millis(30));

        assert_eq!(hb.rtt_samples.len(), 3);
        assert_eq!(hb.missed_count, 0);

        let avg = hb.average_rtt().unwrap();
        assert_eq!(avg, Duration::from_millis(20));
    }

    #[test]
    fn test_heartbeat_max_rtt() {
        let mut hb = HeartbeatState::new();
        hb.record_heartbeat(Duration::from_millis(5));
        hb.record_heartbeat(Duration::from_millis(50));
        hb.record_heartbeat(Duration::from_millis(15));

        assert_eq!(hb.max_rtt(), Some(Duration::from_millis(50)));
    }

    #[test]
    fn test_heartbeat_p99_rtt() {
        let mut hb = HeartbeatState::new();
        for i in 1..=100 {
            hb.record_heartbeat(Duration::from_millis(i));
        }
        let p99 = hb.p99_rtt().unwrap();
        assert!(p99 >= Duration::from_millis(99));
    }

    #[test]
    fn test_heartbeat_miss() {
        let mut hb = HeartbeatState::new();
        hb.record_miss();
        hb.record_miss();
        assert_eq!(hb.missed_count, 2);

        hb.record_heartbeat(Duration::from_millis(10));
        assert_eq!(hb.missed_count, 0); // reset on success
    }

    #[test]
    fn test_heartbeat_samples_bounded() {
        let mut hb = HeartbeatState::new();
        hb.max_rtt_samples = 5;

        for i in 0..10 {
            hb.record_heartbeat(Duration::from_millis(i));
        }
        assert_eq!(hb.rtt_samples.len(), 5);
    }

    // === RemoteWatcher Tests ===

    #[test]
    fn test_watch_and_unwatch() {
        let mut watcher = RemoteWatcher::new(RemoteWatcherConfig::default());
        let target = test_target(2551, "/user/actor-a");

        watcher.watch("/user/watcher", target.clone()).unwrap();
        assert_eq!(watcher.watched_count(), 1);
        assert_eq!(watcher.watcher_count(), 1);

        watcher.unwatch("/user/watcher", &target);
        assert_eq!(watcher.watched_count(), 0);
        assert_eq!(watcher.watcher_count(), 0);
    }

    #[test]
    fn test_watch_multiple_targets() {
        let mut watcher = RemoteWatcher::new(RemoteWatcherConfig::default());
        let t1 = test_target(2551, "/user/a");
        let t2 = test_target(2552, "/user/b");

        watcher.watch("/user/watcher", t1).unwrap();
        watcher.watch("/user/watcher", t2).unwrap();

        assert_eq!(watcher.watched_count(), 2);
        assert_eq!(watcher.watcher_count(), 1);
    }

    #[test]
    fn test_watch_quarantined_node_fails() {
        let mut watcher = RemoteWatcher::new(RemoteWatcherConfig::default());
        let addr = test_address(2551);

        watcher.quarantine_node(&addr, QuarantineReason::ManualQuarantine);

        let target = WatchTarget::new(addr, "/user/a");
        assert!(watcher.watch("/user/w", target).is_err());
    }

    #[test]
    fn test_heartbeat_received_marks_reachable() {
        let mut watcher = RemoteWatcher::new(RemoteWatcherConfig::default());
        let addr = test_address(2551);
        let target = test_target(2551, "/user/a");

        watcher.watch("/user/w", target).unwrap();
        watcher.heartbeat_received(&addr, Duration::from_millis(5));

        assert_eq!(
            watcher.get_node_status(&addr),
            Some(&NodeStatus::Reachable)
        );
    }

    #[test]
    fn test_heartbeat_recovery_from_unreachable() {
        let mut watcher = RemoteWatcher::new(RemoteWatcherConfig::default());
        let addr = test_address(2551);

        // Manually set unreachable
        watcher.nodes.insert(addr.clone(), NodeStatus::Unreachable { since: Instant::now() });
        watcher.heartbeats.insert(addr.clone(), HeartbeatState::new());

        watcher.heartbeat_received(&addr, Duration::from_millis(5));

        let events = watcher.drain_events();
        assert!(events.iter().any(|e| matches!(e, WatchEvent::Reachable { .. })));
        assert!(watcher.get_node_status(&addr).unwrap().is_reachable());
    }

    #[test]
    fn test_actor_terminated() {
        let mut watcher = RemoteWatcher::new(RemoteWatcherConfig::default());
        let target = test_target(2551, "/user/a");

        watcher.watch("/user/w", target.clone()).unwrap();
        watcher.actor_terminated(&target);

        let events = watcher.drain_events();
        assert_eq!(events.len(), 1);
        assert!(matches!(&events[0], WatchEvent::Terminated { address_terminated: false, .. }));
    }

    #[test]
    fn test_quarantine_node() {
        let mut watcher = RemoteWatcher::new(RemoteWatcherConfig::default());
        let addr = test_address(2551);

        watcher.quarantine_node(&addr, QuarantineReason::HandshakeFailure);

        assert!(watcher.is_quarantined(&addr));
        assert!(watcher.get_node_status(&addr).unwrap().is_quarantined());
        assert_eq!(watcher.quarantined_nodes().len(), 1);
    }

    #[test]
    fn test_check_heartbeats_timeout() {
        let config = RemoteWatcherConfig {
            heartbeat_timeout: Duration::from_millis(0), // immediate timeout
            max_heartbeat_misses: 2,
            quarantine_after_misses: 4,
            ..Default::default()
        };
        let mut watcher = RemoteWatcher::new(config);
        let addr = test_address(2551);

        // Manually create stale heartbeat
        let mut hb = HeartbeatState::new();
        hb.last_heartbeat = Instant::now() - Duration::from_secs(10);
        watcher.heartbeats.insert(addr.clone(), hb);
        watcher.nodes.insert(addr.clone(), NodeStatus::Reachable);

        // First check: records miss
        watcher.check_heartbeats();
        // Second check: records another miss → unreachable (2 >= max_heartbeat_misses)
        let events = watcher.check_heartbeats();

        assert!(events.iter().any(|e| matches!(e, WatchEvent::Unreachable { .. })));
    }

    #[test]
    fn test_stats() {
        let mut watcher = RemoteWatcher::new(RemoteWatcherConfig::default());
        let target = test_target(2551, "/user/a");
        let addr = test_address(2551);

        watcher.watch("/user/w", target.clone()).unwrap();
        watcher.heartbeat_received(&addr, Duration::from_millis(5));
        watcher.unwatch("/user/w", &target);

        let stats = watcher.stats();
        assert_eq!(stats.total_watches, 1);
        assert_eq!(stats.total_unwatches, 1);
        assert_eq!(stats.total_heartbeats_received, 1);
    }

    #[test]
    fn test_monitored_nodes() {
        let mut watcher = RemoteWatcher::new(RemoteWatcherConfig::default());
        watcher.watch("/user/w", test_target(2551, "/user/a")).unwrap();
        watcher.watch("/user/w", test_target(2552, "/user/b")).unwrap();

        assert_eq!(watcher.monitored_nodes().len(), 2);
    }

    #[test]
    fn test_quarantine_reason_variants() {
        let reasons = vec![
            QuarantineReason::HeartbeatTimeout,
            QuarantineReason::HandshakeFailure,
            QuarantineReason::ProtocolError("bad frame".into()),
            QuarantineReason::ManualQuarantine,
        ];
        assert_eq!(reasons.len(), 4);
        assert_ne!(reasons[0], reasons[1]);
    }

    #[test]
    fn test_remote_address_display() {
        let addr = test_address(2551);
        let s = format!("{}", addr);
        assert!(s.contains("127.0.0.1"));
        assert!(s.contains("2551"));
    }
}
