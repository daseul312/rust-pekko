// remote_watcher.rs - Remote Actor Death Watch & Node Monitoring
// Akka-like remote watching: track remote actor liveness, quarantine failed nodes

use std::collections::{HashMap, HashSet};
use std::time::{Duration, Instant};

use crate::addressing::RemoteAddress;

// ============================================================================
// Watch Types
// ============================================================================

/// Unique identifier for a watched entity
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct WatchTarget {
    pub address: RemoteAddress,
    pub actor_path: String,
}

impl WatchTarget {
    pub fn new(address: RemoteAddress, path: &str) -> Self {
        Self {
            address,
            actor_path: path.to_string(),
        }
    }
}

/// Event generated by the remote watcher
#[derive(Debug, Clone, PartialEq)]
pub enum WatchEvent {
    /// Remote actor terminated
    Terminated {
        target: WatchTarget,
        address_terminated: bool,
    },
    /// Remote node became unreachable
    Unreachable {
        address: RemoteAddress,
        since: Instant,
    },
    /// Remote node became reachable again
    Reachable {
        address: RemoteAddress,
    },
    /// Remote node quarantined (permanently failed)
    Quarantined {
        address: RemoteAddress,
        reason: QuarantineReason,
    },
}

#[derive(Debug, Clone, PartialEq)]
pub enum QuarantineReason {
    HeartbeatTimeout,
    HandshakeFailure,
    ProtocolError(String),
    ManualQuarantine,
}

// ============================================================================
// Node Status
// ============================================================================

#[derive(Debug, Clone, PartialEq)]
pub enum NodeStatus {
    Unknown,
    Reachable,
    Unreachable { since: Instant },
    Quarantined { since: Instant, reason: QuarantineReason },
}

impl NodeStatus {
    pub fn is_reachable(&self) -> bool {
        matches!(self, NodeStatus::Reachable)
    }

    pub fn is_quarantined(&self) -> bool {
        matches!(self, NodeStatus::Quarantined { .. })
    }

    pub fn is_unreachable(&self) -> bool {
        matches!(self, NodeStatus::Unreachable { .. })
    }
}

// ============================================================================
// Heartbeat Tracker
// ============================================================================

#[derive(Debug, Clone)]
pub struct HeartbeatState {
    pub last_heartbeat: Instant,
    pub missed_count: u32,
    pub rtt_samples: Vec<Duration>,
    pub max_rtt_samples: usize,
}

impl HeartbeatState {
    pub fn new() -> Self {
        Self {
            last_heartbeat: Instant::now(),
            missed_count: 0,
            rtt_samples: Vec::new(),
            max_rtt_samples: 50,
        }
    }

    pub fn record_heartbeat(&mut self, rtt: Duration) {
        self.last_heartbeat = Instant::now();
        self.missed_count = 0;
        if self.rtt_samples.len() >= self.max_rtt_samples {
            self.rtt_samples.remove(0);
        }
        self.rtt_samples.push(rtt);
    }

    pub fn record_miss(&mut self) {
        self.missed_count += 1;
    }

    pub fn elapsed_since_last(&self) -> Duration {
        self.last_heartbeat.elapsed()
    }

    pub fn average_rtt(&self) -> Option<Duration> {
        if self.rtt_samples.is_empty() {
            return None;
        }
        let total: Duration = self.rtt_samples.iter().sum();
        Some(total / self.rtt_samples.len() as u32)
    }

    pub fn max_rtt(&self) -> Option<Duration> {
        self.rtt_samples.iter().max().copied()
    }

    pub fn p99_rtt(&self) -> Option<Duration> {
        if self.rtt_samples.is_empty() {
            return None;
        }
        let mut sorted = self.rtt_samples.clone();
        sorted.sort();
        let idx = ((sorted.len() as f64) * 0.99).ceil() as usize - 1;
        Some(sorted[idx.min(sorted.len() - 1)])
    }
}

