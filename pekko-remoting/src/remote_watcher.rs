#[derive(Debug, Clone)]
pub struct RemoteWatcherConfig {
    pub heartbeat_interval: Duration,
    pub heartbeat_timeout: Duration,
    pub max_heartbeat_misses: u32,
    pub quarantine_after_misses: u32,
    pub unreachable_recheck_interval: Duration,
    pub watch_failure_detector_threshold: f64,
}

impl Default for RemoteWatcherConfig {
    fn default() -> Self {
        Self {
            heartbeat_interval: Duration::from_secs(1),
            heartbeat_timeout: Duration::from_secs(5),
            max_heartbeat_misses: 5,
            quarantine_after_misses: 10,
            unreachable_recheck_interval: Duration::from_secs(3),
            watch_failure_detector_threshold: 8.0,
        }
    }
}

#[derive(Debug)]
pub struct RemoteWatcher {
    config: RemoteWatcherConfig,
    /// Node address → status
    nodes: HashMap<RemoteAddress, NodeStatus>,
    /// Node address → heartbeat state
    heartbeats: HashMap<RemoteAddress, HeartbeatState>,
    /// Watcher path → set of targets being watched
    watches: HashMap<String, HashSet<WatchTarget>>,
    /// Target → set of watcher paths
    reverse_watches: HashMap<WatchTarget, HashSet<String>>,
    /// Quarantined nodes
    quarantined: HashSet<RemoteAddress>,
    /// Pending events
    events: Vec<WatchEvent>,
    /// Stats
    stats: WatcherStats,
}

#[derive(Debug, Clone, Default)]
pub struct WatcherStats {
    pub total_watches: u64,
    pub total_unwatches: u64,
    pub total_terminated: u64,
    pub total_unreachable: u64,
    pub total_quarantined: u64,
    pub total_heartbeats_sent: u64,
    pub total_heartbeats_received: u64,
}

impl RemoteWatcher {
    pub fn new(config: RemoteWatcherConfig) -> Self {
        Self {
            config,
            nodes: HashMap::new(),
            heartbeats: HashMap::new(),
            watches: HashMap::new(),
            reverse_watches: HashMap::new(),
            quarantined: HashSet::new(),
            events: Vec::new(),
            stats: WatcherStats::default(),
        }
    }

    /// Start watching a remote actor
    pub fn watch(&mut self, watcher_path: &str, target: WatchTarget) -> Result<(), String> {
        if self.quarantined.contains(&target.address) {
            return Err(format!(
                "Cannot watch actor on quarantined node: {}",
                target.address
            ));
        }

        // Register the watch
        self.watches
            .entry(watcher_path.to_string())
            .or_default()
            .insert(target.clone());

        self.reverse_watches
            .entry(target.clone())
            .or_default()
            .insert(watcher_path.to_string());

        // Ensure node is tracked
        self.nodes
            .entry(target.address.clone())
            .or_insert(NodeStatus::Unknown);

        self.heartbeats
            .entry(target.address.clone())
            .or_insert_with(HeartbeatState::new);

        self.stats.total_watches += 1;
        Ok(())
    }

    /// Stop watching a remote actor
    pub fn unwatch(&mut self, watcher_path: &str, target: &WatchTarget) {
        if let Some(targets) = self.watches.get_mut(watcher_path) {
            targets.remove(target);
            if targets.is_empty() {
                self.watches.remove(watcher_path);
            }
        }

        if let Some(watchers) = self.reverse_watches.get_mut(target) {
            watchers.remove(watcher_path);
            if watchers.is_empty() {
                self.reverse_watches.remove(target);
            }
        }

        self.stats.total_unwatches += 1;
    }

    /// Record heartbeat received from a node
    pub fn heartbeat_received(&mut self, address: &RemoteAddress, rtt: Duration) {
        self.stats.total_heartbeats_received += 1;

        if let Some(hb) = self.heartbeats.get_mut(address) {
            hb.record_heartbeat(rtt);
        }

        // Update node status to Reachable
        if let Some(status) = self.nodes.get(address) {
            if status.is_unreachable() {
                self.nodes.insert(address.clone(), NodeStatus::Reachable);
                self.events.push(WatchEvent::Reachable {
                    address: address.clone(),
                });
            } else if !status.is_reachable() {
                // Unknown → Reachable (first heartbeat)
                self.nodes.insert(address.clone(), NodeStatus::Reachable);
            }
        } else {
            self.nodes.insert(address.clone(), NodeStatus::Reachable);
        }
    }

    /// Check for heartbeat timeouts and update node statuses
    pub fn check_heartbeats(&mut self) -> Vec<WatchEvent> {
        let mut new_events = Vec::new();
        let config = self.config.clone();

        let addresses: Vec<RemoteAddress> = self.heartbeats.keys().cloned().collect();

        for address in addresses {
            if self.quarantined.contains(&address) {
                continue;
            }

            let should_mark_unreachable;
            let should_quarantine;

            if let Some(hb) = self.heartbeats.get_mut(&address) {
                let elapsed = hb.elapsed_since_last();

                if elapsed > config.heartbeat_timeout {
                    hb.record_miss();
                }

                should_mark_unreachable = hb.missed_count >= config.max_heartbeat_misses;
                should_quarantine = hb.missed_count >= config.quarantine_after_misses;
            } else {
                continue;
            }

            if should_quarantine {
                self.quarantine_node(
                    &address,
                    QuarantineReason::HeartbeatTimeout,
                );
                new_events.push(WatchEvent::Quarantined {
                    address: address.clone(),
                    reason: QuarantineReason::HeartbeatTimeout,
                });
                // Notify all watchers of terminated actors on this node
                let terminated = self.notify_address_terminated(&address);
                new_events.extend(terminated);
            } else if should_mark_unreachable {
                let current = self.nodes.get(&address);
                if !matches!(current, Some(NodeStatus::Unreachable { .. })) {
                    let now = Instant::now();
                    self.nodes
                        .insert(address.clone(), NodeStatus::Unreachable { since: now });
                    new_events.push(WatchEvent::Unreachable {
                        address: address.clone(),
                        since: now,
                    });
                    self.stats.total_unreachable += 1;
                }
            }
        }

        self.events.extend(new_events.clone());
        new_events
    }

    /// Manually quarantine a node
    pub fn quarantine_node(&mut self, address: &RemoteAddress, reason: QuarantineReason) {
        self.quarantined.insert(address.clone());
        self.nodes.insert(
            address.clone(),
            NodeStatus::Quarantined {
                since: Instant::now(),
                reason,
            },
        );
        self.stats.total_quarantined += 1;
    }

    /// Notify watchers that all actors on a given address are terminated
    fn notify_address_terminated(&mut self, address: &RemoteAddress) -> Vec<WatchEvent> {
        let mut events = Vec::new();

        let targets_on_address: Vec<WatchTarget> = self
            .reverse_watches
            .keys()
            .filter(|t| t.address == *address)
            .cloned()
            .collect();

        for target in targets_on_address {
            events.push(WatchEvent::Terminated {
                target: target.clone(),
                address_terminated: true,
            });
            self.stats.total_terminated += 1;
        }

        events
    }

    /// Notify that a specific actor terminated
    pub fn actor_terminated(&mut self, target: &WatchTarget) {
        self.events.push(WatchEvent::Terminated {
            target: target.clone(),
            address_terminated: false,
        });
        self.stats.total_terminated += 1;

        // Clean up watches for this target
        if let Some(watchers) = self.reverse_watches.remove(target) {
            for watcher in &watchers {
                if let Some(targets) = self.watches.get_mut(watcher) {
                    targets.remove(target);
                }
            }
        }
    }

    /// Drain pending events
    pub fn drain_events(&mut self) -> Vec<WatchEvent> {
        std::mem::take(&mut self.events)
    }

    pub fn get_node_status(&self, address: &RemoteAddress) -> Option<&NodeStatus> {
        self.nodes.get(address)
    }

    pub fn get_heartbeat_state(&self, address: &RemoteAddress) -> Option<&HeartbeatState> {
        self.heartbeats.get(address)
    }

    pub fn is_quarantined(&self, address: &RemoteAddress) -> bool {
        self.quarantined.contains(address)
    }

    pub fn quarantined_nodes(&self) -> &HashSet<RemoteAddress> {
        &self.quarantined
    }

    pub fn watched_count(&self) -> usize {
        self.reverse_watches.len()
    }

    pub fn watcher_count(&self) -> usize {
        self.watches.len()
    }

    pub fn monitored_nodes(&self) -> Vec<&RemoteAddress> {
        self.nodes.keys().collect()
    }

    pub fn stats(&self) -> &WatcherStats {
        &self.stats
    }
}

